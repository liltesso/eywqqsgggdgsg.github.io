"""Generate improved Ukraine oblast SVG paths.
Projection: x=(lon-22.0)/18.5*1000, y=(52.5-lat)/8.5*660
Each polygon is slightly larger than real territory so adjacent oblasts overlap
(ensuring no gaps). The uaClip clipPath handles the country border.
"""
import re

def s(lon, lat):
    x = round((lon - 22.0) / 18.5 * 1000, 1)
    y = round((52.5 - lat) / 8.5 * 660, 1)
    return x, y

def path(pts):
    c = [s(lo, la) for lo, la in pts]
    return 'M ' + ' L '.join(f'{x},{y}' for x,y in c) + ' Z'

