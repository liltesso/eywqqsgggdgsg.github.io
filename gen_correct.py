"""Generate geographically correct SVG oblast paths for Ukraine.

Projection: x=(lon-22.0)/18.5*1000, y=(52.5-lat)/8.5*660
SVG viewBox: 0 0 1000 660
"""

import re

def to_svg(lon, lat):
    x = (lon - 22.0) / 18.5 * 1000
    y = (52.5 - lat) / 8.5 * 660
    return (round(x, 1), round(y, 1))

def path(pts):
    coords = [to_svg(lon, lat) for lon, lat in pts]
    parts = ["M"] + [f"{x},{y}" for x,y in coords] + ["Z"]
    return " ".join(["M " + parts[1]] + ["L " + p for p in parts[2:-1]] + ["Z"])

